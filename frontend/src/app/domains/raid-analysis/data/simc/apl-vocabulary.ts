// Every SimulationCraft token the builder knows and what becomes of it; a token outside these tables is reported by the ingest run as a gap.
type AplSupport =
  | 'rule'
  | 'read'
  | 'gate'
  | 'erased'
  | 'opaque'
  | 'ignored';

// rule: shapes a rule. read: a fact no kind consumes yet. gate: talents, hero tree, tier or an inlined variable. erased: sim-only, dropped as its operator's identity. opaque: a literal no kind reads. ignored: parsed and skipped.
export interface AplVocabularyEntry {
  support: AplSupport;
  note: string;
  /** Every path under the shape shares this entry, for families whose fields are all alike (gear, sim scenario, another action's state). */
  subtree?: boolean;
}

